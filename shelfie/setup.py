"""First-run setup, format settings, project launcher and permission rule."""
from __future__ import annotations

import json
import os
import shlex
from pathlib import Path

from . import formats, render, store



def default_plugin_root() -> str:
    return os.environ.get("CLAUDE_PLUGIN_ROOT") or str(Path(__file__).resolve().parents[1])


def _check(names: list) -> list:
    bad = [n for n in names if n not in formats.TYPES]
    if bad:
        raise ValueError(f"unknown format(s): {', '.join(bad)} (known: {', '.join(formats.ALL)})")
    return [t for t in formats.ALL if t in names]


def refresh_launcher(root: Path, plugin_root: str | None = None) -> Path:
    plugin_root = plugin_root or default_plugin_root()
    launcher = store.shelfie_dir(root) / "bin" / "shelfie"
    launcher.parent.mkdir(parents=True, exist_ok=True)
    project = shlex.quote(str(Path(root).absolute()))
    entry = shlex.quote(f"{plugin_root}/bin/shelfie")
    text = ("#!/bin/sh\n# Generated by Shelfie; refreshed every session.\n"
            f'CLAUDE_PROJECT_DIR={project} exec python3 {entry} "$@"\n')
    if not launcher.exists() or launcher.read_text() != text:
        launcher.write_text(text)
    launcher.chmod(0o755)
    return launcher


def launcher_command(root: Path) -> str:
    """The launcher as Claude should type it (absolute, shell-quoted)."""
    return shlex.quote(str(Path(root).absolute() / ".shelfie" / "bin" / "shelfie"))


def _allow_rules(root: Path) -> list:
    return [f"Bash({launcher_command(root)} note:*)"]


def add_permission(root: Path) -> None:
    f = Path(root) / ".claude" / "settings.local.json"
    data = json.loads(f.read_text("utf-8")) if f.exists() else {}
    allow = data.setdefault("permissions", {}).setdefault("allow", [])
    for rule in _allow_rules(root):
        if rule not in allow:
            allow.append(rule)
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", "utf-8")


def run_setup(root: Path, formats_on: list, allow_permission: bool,
              plugin_root: str | None = None) -> None:
    formats_on = _check(formats_on)
    cfg = store.load_config(root) or {"version": 1, "exclude": []}
    cfg["formats"] = formats_on
    cfg.setdefault("exclude", [])
    store.save_config(root, cfg)
    refresh_launcher(root, plugin_root)
    if allow_permission:
        add_permission(root)
    render.render(root)


def set_formats(root: Path, enable: list, disable: list) -> list:
    cfg = store.load_config(root)
    if cfg is None:
        raise RuntimeError("Shelfie is not set up in this project yet")
    _check(list(enable) + list(disable))
    on = (set(cfg["formats"]) | set(enable)) - set(disable)
    cfg["formats"] = [t for t in formats.ALL if t in on]
    store.save_config(root, cfg)
    render.render(root)
    return cfg["formats"]


def setup_context(plugin_root: str | None = None) -> str:
    plugin_root = plugin_root or default_plugin_root()
    labels = ", ".join(f"{t['label']} ({k})" for k, t in formats.TYPES.items())
    return (
        "Shelfie (artifact log plugin) is installed in this project but not set up yet. "
        "At a natural moment early in this conversation, ask the user two things:\n"
        f"1. Which formats to track — {labels}. Default: all.\n"
        "2. Whether Shelfie may record notes without permission prompts — this adds one allow rule "
        "for its own command (.shelfie/bin/shelfie) to .claude/settings.local.json (personal, not committed).\n"
        f'Then run: "{plugin_root}/bin/shelfie" setup --formats all|<keys,comma-separated> '
        "--allow-permission yes|no\n"
        "Until then nothing is tracked."
    )
